"""The documents of the site: the theses and every other file under /files/ that is not a picture.

They live on the web server and not in this repository. A file that was once committed stays in the
history, so a student's request to remove a thesis would mean rewriting that history, and every clone
would carry hundreds of megabytes. data/documents.yaml lists them, so the build can test every link
without having the files. A machine that does have them keeps them in static/files/, which git ignores.

    python tools/documents.py scan                  # bring the list up to date with static/files/
    python tools/documents.py status TARGET         # compare the list with the server; --full also compares the contents
    python tools/documents.py upload TARGET         # put what the server lacks on it; --only /files/x.pdf for one document
    python tools/documents.py download TARGET       # fetch what this machine lacks, for a second copy
    python tools/documents.py remove TARGET /files/x.pdf   # off the server, off the list and off this machine

TARGET is user@spinlab.vu.nl:/folder/of/the/site. Run this from the root of the repository.
"""
import argparse
import hashlib
import json
import os
import shlex
import subprocess
import sys
import tarfile

import yaml

LIST = "data/documents.yaml"
STATIC_DIR = "static"
FILES_DIR = "files"
DEFAULT_KEY = "~/.ssh/spinlab_ed25519"
IMAGE_EXTENSIONS = (".jpg", ".jpeg", ".png", ".gif", ".webp", ".svg")
HEADER = """# Every document on the web server, generated by tools/documents.py. The files are not in this
# repository. The build counts a link to a document as working when the document is on this list, and
# the deploy stops when the server does not hold what this list says.
#
# To add or remove a document, see "Documents" in CLAUDE.md. Do not edit this file by hand.

documents:
"""


def is_document(path):
    # the build writes an index.html into every folder under /files/ to close it
    return (path.startswith(f"/{FILES_DIR}/") and not path.endswith("/")
            and not path.lower().endswith(IMAGE_EXTENSIONS) and not path.endswith("/index.html"))


def load_list():
    return yaml.safe_load(open(LIST, encoding="utf-8"))["documents"] or {}


def save_list(documents):
    with open(LIST, "w", encoding="utf-8", newline="\n") as fn:
        fn.write(HEADER)
        # written by hand and not by yaml, which spreads a long name over two lines; a quoted string is valid in both
        for path, facts in sorted(documents.items()):
            fn.write(f'  {json.dumps(path, ensure_ascii=False)}: {{bytes: {facts["bytes"]}, sha256: "{facts["sha256"]}"}}\n')


def local_path(path):
    return STATIC_DIR + path


def facts_of(path):
    with open(local_path(path), "rb") as fn:
        return {"bytes": os.path.getsize(local_path(path)), "sha256": hashlib.file_digest(fn, "sha256").hexdigest()}


def add_to_list(path):
    documents = load_list()
    documents[path] = facts_of(path)
    save_list(documents)


def ssh_command(target, key, remote):
    host, _, folder = target.partition(":")
    if not folder:
        sys.exit(f"Give the target as user@host:/folder, not {target}")
    return ["ssh", "-i", os.path.expanduser(key), "-o", "BatchMode=yes", "-o", "ConnectTimeout=30", "-o", "StrictHostKeyChecking=accept-new",
            host, f"cd {shlex.quote(folder)} && {remote}"]


def on_server(target, key, remote):
    answer = subprocess.run(ssh_command(target, key, remote), capture_output=True, text=True, encoding="utf-8")
    if answer.returncode:
        sys.exit(f"The server did not answer: {answer.stderr.strip()}")
    return answer.stdout.splitlines()


def server_sizes(target, key):
    lines = on_server(target, key, f"if [ -d {FILES_DIR} ]; then find {FILES_DIR} -type f -printf '/%p\\t%s\\n'; fi")
    return {path: int(size) for path, size in (line.rsplit("\t", 1) for line in lines)}


def server_hashes(target, key):
    lines = on_server(target, key, f"if [ -d {FILES_DIR} ]; then find {FILES_DIR} -type f -exec sha256sum {{}} +; fi")
    return {"/" + line[66:]: line[:64] for line in lines}


def scan(_):
    # Only adds and updates. A thesis from the form is on the server and on the list, but not on this
    # machine until it is downloaded, and that does not make it gone.
    documents = load_list()
    here = []
    for dir_path, _, file_names in os.walk(f"{STATIC_DIR}/{FILES_DIR}"):
        for name in file_names:
            path = "/" + os.path.relpath(os.path.join(dir_path, name), STATIC_DIR).replace(os.sep, "/")
            if is_document(path):
                here.append(path)
    documents.update({path: facts_of(path) for path in here})
    save_list(documents)
    away = sorted(set(documents) - set(here))
    print(f"{len(documents)} documents on the list, {sum(d['bytes'] for d in documents.values()) / 1e6:.1f} MB; {len(away)} of them not on this machine")
    for path in away:
        print("NOT HERE", path)


def differences(args):
    # what the server lacks or holds differently, and what it holds that is not on the list
    documents = load_list()
    sizes = server_sizes(args.target, args.key)
    wrong = [p for p, d in documents.items() if sizes.get(p) != d["bytes"]]
    if getattr(args, "full", False):
        hashes = server_hashes(args.target, args.key)
        wrong = [p for p, d in documents.items() if hashes.get(p) != d["sha256"]]
    return sorted(wrong), sorted(p for p in sizes if is_document(p) and p not in documents), len(documents)


def status(args):
    wrong, extra, total = differences(args)
    for path in wrong:
        print("MISSING OR DIFFERENT", path)
    for path in extra:
        print("NOT ON THE LIST, but online", path)
    print(f"{total - len(wrong)} of {total} documents are in order on the server, {len(extra)} files there are not on the list")
    if wrong:
        sys.exit(1)


def upload(args):
    paths = [args.only] if args.only else differences(args)[0]
    lacking = [p for p in paths if not os.path.isfile(local_path(p))]
    if lacking:
        sys.exit(f"Not on this machine, so it cannot be uploaded: {lacking}")
    if not paths:
        print("The server already has everything")
        return
    # one connection, and the names travel inside the archive, so no name needs quoting for a shell.
    # umask 002: two accounts write here, so a folder that one of them makes has to stay open to the other
    ssh = subprocess.Popen(ssh_command(args.target, args.key, "umask 002 && tar -xf -"), stdin=subprocess.PIPE)
    with tarfile.open(fileobj=ssh.stdin, mode="w|") as archive:
        for path in paths:
            info = archive.gettarinfo(local_path(path), arcname=path.lstrip("/"))
            info.mode, info.uid, info.gid, info.uname, info.gname = 0o664, 0, 0, "", ""
            with open(local_path(path), "rb") as fn:
                archive.addfile(info, fn)
    ssh.stdin.close()
    if ssh.wait():
        sys.exit("The upload failed. Run it again: it only sends what the server still lacks.")
    print(f"{len(paths)} documents uploaded, {sum(os.path.getsize(local_path(p)) for p in paths) / 1e6:.1f} MB")


def download(args):
    documents = load_list()
    paths = sorted(p for p in documents if not os.path.isfile(local_path(p)))
    if not paths:
        print("This machine already has everything")
        return
    ssh = subprocess.Popen(ssh_command(args.target, args.key, "tar -cf - -T -"), stdin=subprocess.PIPE, stdout=subprocess.PIPE)
    ssh.stdin.write("".join(p.lstrip("/") + "\n" for p in paths).encode("utf-8"))
    ssh.stdin.close()
    with tarfile.open(fileobj=ssh.stdout, mode="r|") as archive:
        archive.extractall(STATIC_DIR, filter="data")
    if ssh.wait():
        sys.exit("The download failed.")
    wrong = [p for p in paths if not os.path.isfile(local_path(p)) or facts_of(p) != documents[p]]
    print(f"{len(paths) - len(wrong)} of {len(paths)} documents fetched and identical to the list")
    if wrong:
        sys.exit(f"Missing or different: {wrong}")


def remove(args):
    documents = load_list()
    if args.path not in documents:
        sys.exit(f"Not on the list: {args.path}")
    on_server(args.target, args.key, f"rm -f -- {shlex.quote(args.path.lstrip('/'))}")
    del documents[args.path]
    save_list(documents)
    if os.path.isfile(local_path(args.path)):
        os.remove(local_path(args.path))
    print("removed", args.path)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(required=True)
    commands.add_parser("scan").set_defaults(run=scan)
    for name, run in (("status", status), ("upload", upload), ("download", download), ("remove", remove)):
        command = commands.add_parser(name)
        command.add_argument("target")
        command.add_argument("--key", default=DEFAULT_KEY)
        command.set_defaults(run=run)
        if name == "status":
            command.add_argument("--full", action="store_true", help="also compare the contents, which reads every file on the server")
        if name == "upload":
            command.add_argument("--only", metavar="PATH")
        if name == "remove":
            command.add_argument("path")
    args = parser.parse_args()
    args.run(args)


if __name__ == "__main__":
    main()
